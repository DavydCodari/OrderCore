CREATE TABLE shopping_carts(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_shopping_carts PRIMARY KEY (id),
    CONSTRAINT fk_shopping_carts_customer FOREIGN KEY (customer_id) REFERENCES users(id)
);

CREATE TABLE cart_items(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_id BIGINT NOT NULL,
    shopping_cart_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    quantity INT NOT NULL,

    CONSTRAINT pk_cart_items PRIMARY KEY (id),
    CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_cart_items_shopping_cart FOREIGN KEY (shopping_cart_id) REFERENCES shopping_carts(id),
    CONSTRAINT ck_cart_items_quantity CHECK (quantity > 0)
);

CREATE INDEX ix_shopping_carts_customer_id ON shopping_carts(customer_id);
CREATE INDEX ix_cart_items_product_id ON cart_items(product_id);
CREATE INDEX ix_cart_items_shopping_cart_id ON cart_items(shopping_cart_id);
